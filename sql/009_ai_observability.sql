CREATE OR REPLACE VIEW ai_generation_daily_metrics AS
SELECT
  date_trunc('day', started_at) AS day,
  operation,
  provider,
  model,
  count(*) AS requests,
  count(*) FILTER (WHERE status = 'failed') AS errors,
  avg(total_duration_ms) AS average_duration_ms,
  percentile_cont(0.95) WITHIN GROUP (ORDER BY total_duration_ms) AS p95_duration_ms,
  percentile_cont(0.99) WITHIN GROUP (ORDER BY total_duration_ms) AS p99_duration_ms,
  avg(total_tokens) AS average_tokens,
  sum(total_tokens) AS total_tokens,
  avg(total_cost_usd) AS average_cost_usd,
  sum(total_cost_usd) AS total_cost_usd,
  avg(retry_count) AS average_retries
FROM ai_generations
GROUP BY 1, 2, 3, 4;

CREATE OR REPLACE VIEW ai_stage_daily_metrics AS
SELECT
  date_trunc('day', stage.created_at) AS day,
  generation.operation,
  generation.provider,
  generation.model,
  stage.stage,
  count(*) AS executions,
  avg(stage.duration_ms) AS average_duration_ms,
  percentile_cont(0.95) WITHIN GROUP (ORDER BY stage.duration_ms) AS p95_duration_ms,
  percentile_cont(0.99) WITHIN GROUP (ORDER BY stage.duration_ms) AS p99_duration_ms,
  count(*) FILTER (WHERE NOT stage.success) AS errors
FROM ai_generation_stages stage
JOIN ai_generations generation ON generation.id = stage.generation_id
GROUP BY 1, 2, 3, 4, 5;

-- Views do not inherit table RLS on every supported PostgreSQL version.
